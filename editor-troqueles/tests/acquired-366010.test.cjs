const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..'),repo=path.resolve(root,'..');
const models=JSON.parse(fs.readFileSync(path.join(root,'dist/assets/modelos.json')));
const caps=JSON.parse(fs.readFileSync(path.join(root,'dist/assets/capacidades-materiales.json')));
const materials=JSON.parse(fs.readFileSync(path.join(root,'dist/assets/materiales.json'))).materials;
const model=models.find(m=>m.id==='366010');
assert.ok(model,'366010 missing');
assert.strictEqual(model.engine,'rigid366010');
assert.ok(model.rule&&model.rule.regimes.length===2);
assert.deepStrictEqual(model.dims,{L:180,W:100,H:40});
assert.deepStrictEqual(model.bounds,{L:[160,220],W:[80,140],H:[30,70]});
assert.strictEqual(model.category,'Rígidas');
assert.strictEqual(model.layer.multiPiece,true);
assert.strictEqual(model.layer.officialBleeds,false);
assert.strictEqual(model.layer.bleedFromCuts,true);
assert.strictEqual(model.layer.bleedPath.split('M').length-1,2);
assert.ok(model.layer.bleedPath.length>5000);
assert.strictEqual(model.layer.faces.length,60);
assert.strictEqual(model.layer.folds.length,56);
assert.strictEqual(model.layer.cuts.length,216);
assert.strictEqual(model.layer.bleeds.length,76);
assert.deepStrictEqual(model.layer.holes,[]);
assert.strictEqual(model.layer.pieceLabels.length,4);
assert.strictEqual(model.layer.totalX,605.5500000000001);
assert.strictEqual(model.layer.totalY,476.70000000000005);

const generated=JSON.parse(fs.readFileSync(path.join(repo,'geometria/modelos/366010/troquel-generado.json')));
assert.deepStrictEqual(generated.dimensiones_manufactura_mm,{L:180,W:100,H:40});
assert.deepStrictEqual(generated.conteos,{piezas:4,caras:60,pliegues:56,cortes:216,sangrados:76,orificios:0});
for(const key of ['faces','folds','cuts','bleeds','holes'])assert.deepStrictEqual(model.layer[key],generated.compuesto[key],key);
assert.strictEqual(model.layer.bleedPath,generated.compuesto.bleedPath);
assert.strictEqual(generated.piezas.length,4);
for(const piece of generated.piezas){
  assert.ok(piece.extension_mm.x>0&&piece.extension_mm.y>0);
  assert.ok(piece.offset_mm.x>=0&&piece.offset_mm.y>=0);
}

const cap=caps['366010'];
assert.ok(cap,'366010 capability missing');
assert.strictEqual(cap.originalMaterialId,366010);
assert.strictEqual(cap.originalThickness,2);
assert.deepStrictEqual(cap.observedThicknessLimits,[1.5,2.5]);
assert.deepStrictEqual(cap.verifiedThicknessRange,[1.5,2.5]);
assert.deepStrictEqual(model.rule.thicknesses,[1.5,1.75,2,2.25,2.5]);
assert.strictEqual(cap.onlyManufacturing,true);
assert.strictEqual(cap.geometryStatus,'parametric-piecewise');
const material=materials.find(m=>m.id===366010);
assert.ok(material,'366010 material missing');
assert.strictEqual(material.thickness,2);
assert.strictEqual(material.adjustable,true);
assert.strictEqual(material.min,1.5);
assert.strictEqual(material.max,2.5);

const svg=fs.readFileSync(path.join(root,'dist/assets/366010.svg'),'utf8');
assert.ok(svg.includes('<svg'));
assert.strictEqual((svg.match(/-etiqueta/g)||[]).length,4);
assert.ok(!/NaN|Infinity/.test(svg));
const exported=fs.readFileSync(path.join(repo,'geometria/modelos/366010/exportado-editor.svg'),'utf8');
assert.ok(exported.includes('id="corte"')&&exported.includes('id="sangrado"'));
const bleed=exported.match(/id="sangrado"[^>]*d="([^"]+)"/);
assert.ok(bleed,'exported bleed missing');
assert.strictEqual(bleed[1].split('M').length-1,2);
assert.ok(exported.includes('Fondo · cartón gris 2 mm'));
const paramExport=fs.readFileSync(path.join(repo,'geometria/modelos/366010/exportado-editor-210x120x50.svg'),'utf8');
const paramBleed=paramExport.match(/id="sangrado"[^>]*d="([^"]+)"/);
assert.ok(paramBleed,'parametric exported bleed missing');
assert.strictEqual(paramBleed[1].split('M').length-1,2);
assert.ok(paramExport.includes('width="721.95mm"'));
console.log('366010 OK · 4 piezas · 60 caras · 56 pliegues · 216 cortes · 76 sangrados');
